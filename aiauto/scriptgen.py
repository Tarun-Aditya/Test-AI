"""Generate standalone, human-readable Playwright and Selenium scripts from a resolved TestCase,
using each engine's *native* locator API (get_by_role / get_by_label / ... and By.ID / By.NAME / ...).

The scripts
  * keep ${var} placeholders and read values from DATA, or a JSON file passed as the first argument;
  * never contain sensitive values - those come from AIAUTO_SECRET_<KEY> environment variables;
  * embed the portable test spec (script.json) on their last line, so a generated .py can be uploaded
    back into the web app / CLI and re-run on either engine (see extract_spec()).
"""
