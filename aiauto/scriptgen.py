def _sel_key(k: str | None) -> str:
    parts = (k or "Enter").split("+")
    return " + ".join(f"Keys.{SEL_KEYS[p]}" if p in SEL_KEYS else _q(p.lower()) for p in parts)


def se_locator(st: Step, attr: str = "locator") -> Locator | None:
    """First of the step's verified locators that Selenium can execute (Playwright-generated ones can't)."""
    from .engines.selenium_engine import by_for
    primary = getattr(st, attr)
    pool = [primary] + (st.fallbacks if attr == "locator" else [])
    return next((l for l in pool if l and by_for(l, bool(l.shadow))), primary)


def se_alternates(st: Step) -> list[Locator]:
    """Other verified locators Selenium can run (after the primary one): tried in order if the first finds nothing."""
    from .engines.selenium_engine import by_for
    first = se_locator(st)
    return [l for l in [st.locator, *st.fallbacks] if l and l is not first and l != first and by_for(l, bool(l.shadow))][:2]


def se_find(loc: Locator | None, clickable: bool = False, alts: list[Locator] | None = None) -> str:
    if not loc:
        return "None"
    from .engines.selenium_engine import by_for
    by = by_for(loc, bool(loc.shadow))
    if by is None:
        return f"_no_selenium_locator({_q(loc.label())})"
    args = f"{BY_NAME.get(by[0], repr(by[0]))}, {_q(by[1])}"
    if loc.frames:
        args += f", frames={loc.frames!r}"
    if loc.shadow:
        args += f", shadow={loc.shadow!r}"
    if clickable:
        args += ", clickable=True"
    spare = []
    for a in alts or []:
        ab = by_for(a, bool(a.shadow))
        if ab:
            spare.append(f"({BY_NAME.get(ab[0], repr(ab[0]))}, {_q(ab[1])}, {a.frames!r}, {a.shadow!r})")
    if spare:
        args += ", alts=[" + ", ".join(spare) + "]"
    return f"find(driver, {args})"


