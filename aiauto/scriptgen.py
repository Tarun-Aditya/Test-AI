"""Generate standalone, human-readable Playwright and Selenium scripts from a resolved TestCase.

The scripts keep ${var} placeholders and read values from DATA (or a JSON file passed as the
first CLI argument), so the same script can be re-run with different data.
"""
from __future__ import annotations

import json
import pprint

from .models import Action, Step, TestCase

HEADER = '''"""
{name}
Auto-generated by AI Test Automation from plain English. Re-run: python {fname} [data.json]

Original instructions:
{source}
"""
import json
import re
import sys

DATA = {data}
if len(sys.argv) > 1:
    with open(sys.argv[1], encoding="utf-8") as fh:
        DATA.update(json.load(fh))


def v(text):
    """Substitute ${{var}} / {{{{var}}}} placeholders from DATA (dotted paths allowed)."""
    def look(path):
        cur = DATA
        for tok in re.findall(r"[^.\\[\\]]+", path):
            cur = cur[int(tok)] if isinstance(cur, list) else cur[tok]
        return str(cur)
    return re.sub(r"\\$\\{{\\s*([\\w.\\-\\[\\]]+)\\s*\\}}|\\{{\\{{\\s*([\\w.\\-\\[\\]]+)\\s*\\}}\\}}",
                  lambda m: look(m.group(1) or m.group(2)), text)

'''


def _q(s: str | None) -> str:
    return json.dumps(s if s is not None else "")


def _val(s: str | None) -> str:
    """Python expression for a value; wraps in v() only when it has placeholders."""
    if s and ("${" in s or "{{" in s):
        return f"v({_q(s)})"
    return _q(s)


def _comment(st: Step, i: int) -> str:
    raw = (st.raw or f"{st.action.value} {st.target or ''} {st.value or ''}").replace("\n", " ")
    return f"    # Step {i}: {raw}"


def _header(test: TestCase, fname: str) -> str:
    source = "\n".join("    " + l for l in (test.source_text or "").strip().splitlines()) or "    (none)"
    return HEADER.format(name=test.name.replace('"""', "'''"), fname=fname, source=source.replace('"""', "'''"),
                         data=pprint.pformat(test.data, indent=4, sort_dicts=False) if test.data else "{}")


# ------------------------------------------------------------------ Playwright
def playwright_script(test: TestCase) -> str:
    out = [_header(test, "test_playwright.py"),
           "from playwright.sync_api import sync_playwright, expect\n\n",
           "def run(page):"]
    for i, st in enumerate(test.steps, 1):
        out.append(_comment(st, i))
        out.extend("    " + line for line in _pw_lines(st))
    out.append("")
    out.append('''
if __name__ == "__main__":
    import os
    headless = os.getenv("HEADLESS", "0") == "1"
    with sync_playwright() as p:
        browser = p.chromium.launch(headless=headless, executable_path=os.getenv("AIAUTO_CHROME_BINARY") or None)
        video = {} if os.getenv("NO_VIDEO") else {"record_video_dir": "videos/"}
        context = browser.new_context(viewport={"width": 1280, "height": 800}, **video)
        page = context.new_page()
        page.set_default_timeout(10000)
        try:
            run(page)
            print("PASSED")
        finally:
            context.close()
            browser.close()
''')
    return "\n".join(out)


def _pw_sel(st: Step) -> str:
    loc = st.locator
    if not loc:
        return "None"
    prefix = "xpath=" if loc.strategy == "xpath" else ""
    return _q(prefix + loc.value)


def _pw_lines(st: Step) -> list[str]:
    a, sel, val = st.action, _pw_sel(st), _val(st.value)
    L = f"page.locator({sel}).first"
    m = {
        Action.NAVIGATE: [f"page.goto({val})"],
        Action.BACK: ["page.go_back()"],
        Action.REFRESH: ["page.reload()"],
        Action.CLICK: [f"{L}.click()"],
        Action.DOUBLE_CLICK: [f"{L}.dblclick()"],
        Action.RIGHT_CLICK: [f'{L}.click(button="right")'],
        Action.TYPE: [f"{L}.fill({val})"],
        Action.APPEND: [f"{L}.press_sequentially({val})"],
        Action.PRESS: [f"{L}.press({val})" if st.locator else f"page.keyboard.press({val})"],
        Action.HOVER: [f"{L}.hover()"],
        Action.SELECT: [f"{L}.select_option(label={val})"],
        Action.CHECK: [f"{L}.check()"],
        Action.UNCHECK: [f"{L}.uncheck()"],
        Action.UPLOAD: [f"{L}.set_input_files({val})"],
        Action.ASSERT_VISIBLE: [f"expect({L}).to_be_visible()"],
        Action.ASSERT_URL: [f"expect(page).to_have_url(re.compile(re.escape({val})))"],
        Action.ASSERT_TITLE: [f"expect(page).to_have_title(re.compile(re.escape({val})))"],
        Action.ASSERT_TEXT: [f"expect({L}).to_contain_text({val})" if st.locator
                             else f'expect(page.locator("body")).to_contain_text({val})'],
        Action.SCREENSHOT: [f'page.screenshot(path={_q((st.value or "screenshot") + ".png")}, full_page=True)'],
    }
    if a == Action.WAIT:
        return [f"{L}.wait_for()"] if st.locator else [f"page.wait_for_timeout({int(float(st.value or 1) * 1000)})"]
    if a == Action.SCROLL:
        if st.locator:
            return [f"{L}.scroll_into_view_if_needed()"]
        d, _, amt = (st.value or "down").partition(":")
        amt = amt or "600"
        js = {"top": "window.scrollTo(0,0)", "bottom": "window.scrollTo(0, document.body.scrollHeight)",
              "up": f"window.scrollBy(0,-{amt})"}.get(d, f"window.scrollBy(0,{amt})")
        return [f"page.evaluate({_q(js)})"]
    return m.get(a, [f"# unsupported action {a.value}"])


# ------------------------------------------------------------------ Selenium
SEL_KEYS = {"Enter": "ENTER", "Tab": "TAB", "Escape": "ESCAPE", "Space": "SPACE", "Backspace": "BACKSPACE",
            "Delete": "DELETE", "ArrowUp": "ARROW_UP", "ArrowDown": "ARROW_DOWN", "ArrowLeft": "ARROW_LEFT",
            "ArrowRight": "ARROW_RIGHT", "PageUp": "PAGE_UP", "PageDown": "PAGE_DOWN", "Home": "HOME", "End": "END",
            "Control": "CONTROL", "Shift": "SHIFT", "Alt": "ALT", "Meta": "META"}


def _sel_key(k: str | None) -> str:
    parts = (k or "Enter").split("+")
    return " + ".join(f"Keys.{SEL_KEYS[p]}" if p in SEL_KEYS else _q(p.lower()) for p in parts)


def selenium_script(test: TestCase) -> str:
    out = [_header(test, "test_selenium.py"),
           "from selenium import webdriver\n"
           "from selenium.webdriver.common.action_chains import ActionChains\n"
           "from selenium.webdriver.common.by import By\n"
           "from selenium.webdriver.common.keys import Keys\n"
           "from selenium.webdriver.support import expected_conditions as EC\n"
           "from selenium.webdriver.support.ui import Select, WebDriverWait\n\n"
           "TIMEOUT = 10\n\n\n"
           "def find(driver, by, value, clickable=False):\n"
           "    cond = EC.element_to_be_clickable if clickable else EC.presence_of_element_located\n"
           "    return WebDriverWait(driver, TIMEOUT).until(cond((by, value)))\n\n\n"
           "def wait_text(get, expected):\n"
           "    WebDriverWait(None, TIMEOUT).until(lambda _: expected.lower() in (get() or '').lower(),\n"
           "                                       f'expected to find {expected!r}')\n\n\n"
           "def run(driver):"]
    for i, st in enumerate(test.steps, 1):
        out.append(_comment(st, i))
        out.extend("    " + line for line in _se_lines(st))
    out.append('''

if __name__ == "__main__":
    import os
    options = webdriver.ChromeOptions()
    options.add_argument("--window-size=1280,800")
    if os.getenv("HEADLESS", "0") == "1":
        options.add_argument("--headless=new")
        options.add_argument("--no-sandbox")
    if os.getenv("AIAUTO_CHROME_BINARY"):
        options.binary_location = os.environ["AIAUTO_CHROME_BINARY"]
    service = None
    if os.getenv("AIAUTO_CHROMEDRIVER"):
        from selenium.webdriver.chrome.service import Service
        service = Service(os.environ["AIAUTO_CHROMEDRIVER"])
    driver = webdriver.Chrome(options=options, service=service) if service else webdriver.Chrome(options=options)
    try:
        run(driver)
        print("PASSED")
    finally:
        driver.quit()
''')
    return "\n".join(out)


def _se_lines(st: Step) -> list[str]:
    a, val = st.action, _val(st.value)
    if st.locator:
        by = "By.XPATH" if st.locator.strategy == "xpath" else "By.CSS_SELECTOR"
        F = f"find(driver, {by}, {_q(st.locator.value)})"
        FC = f"find(driver, {by}, {_q(st.locator.value)}, clickable=True)"
    else:
        F = FC = "None"
    m = {
        Action.NAVIGATE: [f"driver.get({val})"],
        Action.BACK: ["driver.back()"],
        Action.REFRESH: ["driver.refresh()"],
        Action.CLICK: [f"{FC}.click()"],
        Action.DOUBLE_CLICK: [f"ActionChains(driver).double_click({FC}).perform()"],
        Action.RIGHT_CLICK: [f"ActionChains(driver).context_click({FC}).perform()"],
        Action.TYPE: [f"el = {F}", "el.clear()", f"el.send_keys({val})"],
        Action.APPEND: [f"{F}.send_keys({val})"],
        Action.PRESS: [f"{F}.send_keys({_sel_key(st.value)})" if st.locator
                       else f"ActionChains(driver).send_keys({_sel_key(st.value)}).perform()"],
        Action.HOVER: [f"ActionChains(driver).move_to_element({F}).perform()"],
        Action.SELECT: [f"Select({F}).select_by_visible_text({val})"],
        Action.CHECK: [f"el = {F}", "if not el.is_selected():", "    driver.execute_script('arguments[0].click()', el)"],
        Action.UNCHECK: [f"el = {F}", "if el.is_selected():", "    driver.execute_script('arguments[0].click()', el)"],
        Action.UPLOAD: [f"{F}.send_keys({val})"],
        Action.ASSERT_VISIBLE: [f"assert {F}.is_displayed()"],
        Action.ASSERT_URL: [f"wait_text(lambda: driver.current_url, {val})"],
        Action.ASSERT_TITLE: [f"wait_text(lambda: driver.title, {val})"],
        Action.ASSERT_TEXT: [f"wait_text(lambda: {F}.text or {F}.get_attribute('value'), {val})" if st.locator
                             else f"wait_text(lambda: driver.find_element(By.TAG_NAME, 'body').text, {val})"],
        Action.SCREENSHOT: [f"driver.save_screenshot({_q((st.value or 'screenshot') + '.png')})"],
    }
    if a == Action.WAIT:
        return [F] if st.locator else ["import time", f"time.sleep({float(st.value or 1)})"]
    if a == Action.SCROLL:
        if st.locator:
            return [f"driver.execute_script(\"arguments[0].scrollIntoView({{block:'center'}})\", {F})"]
        d, _, amt = (st.value or "down").partition(":")
        amt = amt or "600"
        js = {"top": "window.scrollTo(0,0)", "bottom": "window.scrollTo(0, document.body.scrollHeight)",
              "up": f"window.scrollBy(0,-{amt})"}.get(d, f"window.scrollBy(0,{amt})")
        return [f"driver.execute_script({_q(js)})"]
    return m.get(a, [f"# unsupported action {a.value}"])
