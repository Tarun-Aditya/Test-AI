# The configuration of the recorded run (browser, headless, viewport, timeouts, video, highlight).
# Environment variables override it: BROWSER, HEADLESS, NO_VIDEO, STEP_TIMEOUT, RESULTS_DIR, STORAGE_STATE, ...
CONFIG = {config}
