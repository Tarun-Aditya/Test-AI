"""Build the Chrome extension's page-side library from the Python source, and zip the extension.

    python tools/build_extension.py            # regenerate extension/lib/shared.js
    python tools/build_extension.py --check    # exit 1 if shared.js is out of date (CI / tests)
    python tools/build_extension.py --zip      # also write dist/autopilot-extension.zip (load it unpacked, or upload it)

shared.js is generated, not edited: the DOM walk that finds candidate elements, the green highlight box, the masking of
secret fields and the page-text reader are the very scripts the Playwright and Selenium engines inject, taken from
aiauto/locators.py and aiauto/script_runtime.py. The extension therefore finds, boxes and reads elements exactly like a
run in the app does.
"""
from __future__ import annotations

import json
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
EXT = ROOT / "extension"


def shared_js() -> str:
    from aiauto import locators, script_runtime as sr
    snap = locators.SNAPSHOT_JS.replace("/*WORDS*/[]", "W__")
    return f"""// GENERATED by tools/build_extension.py from aiauto/locators.py and aiauto/script_runtime.py. Do not edit.
(() => {{
  if (window.__aiautoShared) return;
  // the DOM walk: every actionable element of this document (open shadow roots and same-origin frames included)
  window.__aiautoSnapshot = function (words) {{ var W__ = words || [];
{snap}
  }};
  window.__aiautoShared = {{
    boxCss: {json.dumps(sr.BOX_CSS)},
    box: {sr.HL_BOX_JS},
    clearBox: {sr.HL_CLEAR_JS},
    mask: {sr.MASK_JS},
    pageText: {sr.FRAME_TEXT_JS},
    describe: {locators.DESCRIBE_EL_JS},
  }};
}})();
"""


def open_shadow_js() -> str:
    from aiauto import script_runtime as sr
    return ("// GENERATED by tools/build_extension.py from aiauto/script_runtime.py. Do not edit.\n"
            "// Optional (Settings > Open closed shadow roots): runs before the page's own scripts and makes shadow roots open, so\n"
            "// elements inside them can be found, as the Playwright and Selenium engines do.\n" + sr.OPEN_SHADOW_JS + "\n")


def main() -> int:
    generated = {EXT / "lib" / "shared.js": shared_js(), EXT / "lib" / "open-shadow.js": open_shadow_js()}
    if "--check" in sys.argv:
        stale = [p.relative_to(ROOT) for p, text in generated.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        if stale:
            print(f"{', '.join(map(str, stale))} out of date: run python tools/build_extension.py")
            return 1
        print("extension/lib/shared.js and open-shadow.js are up to date")
        return 0
    for out, text in generated.items():
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")
        print(f"wrote {out.relative_to(ROOT)} ({len(text) // 1024 or 1} KB)")
    if "--zip" in sys.argv:
        dist = ROOT / "dist"
        dist.mkdir(exist_ok=True)
        z = dist / "autopilot-extension.zip"
        with zipfile.ZipFile(z, "w", zipfile.ZIP_DEFLATED) as zf:
            for p in sorted(EXT.rglob("*")):
                if p.is_file() and "node_modules" not in p.parts and p.name != "README.md":
                    zf.write(p, p.relative_to(EXT).as_posix())
        print(f"wrote {z.relative_to(ROOT)} ({z.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
