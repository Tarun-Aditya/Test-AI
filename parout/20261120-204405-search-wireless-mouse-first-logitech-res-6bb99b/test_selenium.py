def answer_alert(driver, accept=True):
    if driver.name == "safari":   # Safari stalls while a native dialog is open: answer them in the page instead
        try:
            return driver.execute_script(DIALOG_SHIM_JS, accept)
        except Exception:
            return None
    try:
        alert = driver.switch_to.alert
        text = alert.text
        alert.accept() if accept else alert.dismiss()
        return text
    except Exception:
        return None


def set_value(driver, el, value):
    driver.execute_script(
        "const s=Object.getOwnPropertyDescriptor(Object.getPrototypeOf(arguments[0]),'value');"
        "s?s.set.call(arguments[0],arguments[1]):arguments[0].value=arguments[1];"
        "arguments[0].dispatchEvent(new Event('input',{bubbles:true}));arguments[0].dispatchEvent(new Event('change',{bubbles:true}));",
        el, value)


def type_into(driver, el, value, clear=True):
    if el.get_attribute("type") in ("date", "time", "range", "color", "month", "week", "datetime-local"):
        return set_value(driver, el, value)
    if el.get_attribute("contenteditable") in ("", "true") and el.tag_name.lower() not in ("input", "textarea"):
        if clear:
            driver.execute_script("arguments[0].textContent = ''", el)
        el.click()
    elif clear:
        el.clear()
    el.send_keys(value)


